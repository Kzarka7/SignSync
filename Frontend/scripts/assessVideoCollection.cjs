        await page.getByRole('img', { name: 'Left hand detections; blank areas mean no detection' }).waitFor()
        await page.getByText('Tracking timeline', { exact: true }).click()
        await page.getByText('Adjust interval', { exact: true }).click()
        await page.getByLabel('Sign start (seconds)').waitFor()
        await page.getByLabel('Expected hand coverage for this take').selectOption('both')
        await page.getByLabel('Expected hand coverage for this take').selectOption('either')
