        if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) throw Error('Mobile upload overflows viewport')
        if (await page.locator('main').evaluate(element => element.clientWidth < 300)) throw Error('Mobile collector is squeezed by navigation')
