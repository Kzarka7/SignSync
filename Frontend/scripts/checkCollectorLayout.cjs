// Isolated layout/export smoke check. Uses existing development fixtures only.
const fs = require('node:fs')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
async function main() {
  const [output, playwrightPath] = process.argv.slice(2)
  const { chromium } = require(playwrightPath)
  const { createServer } = await import(pathToFileURL(path.resolve(__dirname, '../node_modules/vite/dist/node/index.js')))
  const server = await createServer({ root: path.resolve(__dirname, '..'), server: { host: '127.0.0.1', port: 5196, strictPort: true, hmr: false } })
  let browser
  try {
    await server.listen()
    browser = await chromium.launch({ channel: 'msedge', headless: true })
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    await page.goto('http://127.0.0.1:5196/dataset-collector')
    await page.getByRole('button', { name: 'Upload videos', exact: true }).click()
    const checkboxBelowFiles = await page.getByLabel('Auto-trim and reprocess new recordings', { exact: true }).evaluate(input =>
      input.getBoundingClientRect().top > document.querySelector('input[type=file]').getBoundingClientRect().bottom)
    if (!checkboxBelowFiles) throw Error('Upload checkboxes must stay below Choose Files')
    const layout = await page.evaluate(() => {
      const box = selector => {
        const r = document.querySelector(selector).getBoundingClientRect()
        return { x: r.x, y: r.y, width: r.width, height: r.height }
      }
      return { controls: box('[data-collector-controls]'), preview: box('[data-collector-preview]'), review: box('[data-collector-review]') }
    })
    if (layout.preview.x >= layout.review.x || Math.abs(layout.review.y - layout.controls.y - layout.controls.height - 16) > 1 ||
      Math.abs(layout.controls.x - layout.review.x) > 1 || Math.abs(layout.controls.width - layout.review.width) > 1)
      throw Error('Collector does not follow the two-column sketch: ' + JSON.stringify(layout))
    await page.screenshot({ path: path.join(output, 'final-empty-desktop.png'), fullPage: true })
    await page.getByLabel('Auto-trim and reprocess new recordings', { exact: true }).uncheck()
    await page.getByLabel('Auto-trim and reprocess new recordings', { exact: true }).check()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: 'Open sidebar', exact: true }).waitFor()
    await page.screenshot({ path: path.join(output, 'final-empty-mobile.png'), fullPage: true })
    const mainWidth = await page.locator('main').evaluate(element => element.clientWidth)
    if (mainWidth < 300) throw Error('Collector width is constrained by navigation')
    await page.getByRole('button', { name: 'Open sidebar', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Navigation', exact: true })
    await dialog.waitFor()
    await page.keyboard.press('Shift+Tab')
    if (!await dialog.evaluate(element => element.contains(document.activeElement))) throw Error('Navigation focus escaped')
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Open sidebar', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Open sidebar', exact: true }).click()
    await page.getByRole('button', { name: 'Close navigation', exact: true }).click({ position: { x: 380, y: 100 } })
    await page.getByRole('button', { name: 'Open sidebar', exact: true }).waitFor()
    await page.setViewportSize({ width: 1440, height: 1000 })
    const samples = JSON.parse(fs.readFileSync(path.join(output, 'batch-saved-samples.json')))
    await page.evaluate(samples => localStorage.setItem('daloy:dataset-sequences', JSON.stringify(samples)), samples)
    await page.reload()
    await page.getByRole('button', { name: 'Upload videos', exact: true }).click()
    await page.getByText('Recorded samples (2)', { exact: true }).waitFor()
    await page.getByText('Recorded samples (2)', { exact: true }).click()
    if (await page.getByRole('button', { name: 'Prepare training package', exact: true }).isVisible()) throw Error('Recorded samples did not collapse')
    await page.getByText('Recorded samples (2)', { exact: true }).click()
    await page.getByRole('button', { name: 'Prepare training package', exact: true }).click()
    await page.getByRole('button', { name: 'Download training package', exact: true }).waitFor()
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Download training package', exact: true }).click()
    await (await download).saveAs(path.join(output, 'final-layout-training-package.zip'))
    await page.getByText('Sample exports and storage', { exact: true }).click()
    await page.getByRole('button', { name: 'Export JSON', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Prepare ZIP', exact: true }).waitFor()
    await page.screenshot({ path: path.join(output, 'final-saved-desktop.png'), fullPage: true })
    await page.getByRole('button', { name: 'Delete THANK_YOU sample', exact: true }).first().click()
    await page.getByText('Recorded samples (1)', { exact: true }).waitFor()
    if (await page.evaluate(() => JSON.parse(localStorage.getItem('daloy:dataset-sequences')).length) !== 1) throw Error('Saved deletion failed')
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: 'Open sidebar', exact: true }).waitFor()
    await page.screenshot({ path: path.join(output, 'final-saved-mobile.png'), fullPage: true })
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) throw Error('Saved layout overflows viewport')
    if (process.env.BOUNDARY_SAMPLES_FIXTURE) {
      const boundarySamples = JSON.parse(fs.readFileSync(process.env.BOUNDARY_SAMPLES_FIXTURE))
      await page.evaluate(samples => localStorage.setItem('daloy:dataset-sequences', JSON.stringify(samples)), boundarySamples)
      await page.reload()
      await page.getByRole('button', { name: 'Rest and Idle Collector', exact: true }).click()
      await page.getByRole('button', { name: 'Idle movements', exact: true }).click()
      await page.getByRole('button', { name: 'Upload videos', exact: true }).click()
      await page.setViewportSize({ width: 1440, height: 1000 })
      const columns = await page.evaluate(() => {
        const upload = document.querySelector('[data-collector-upload]').parentElement.getBoundingClientRect()
        const preview = document.querySelector('[data-collector-preview]').getBoundingClientRect()
        const controls = document.querySelector('[data-collector-controls]').getBoundingClientRect()
        const queue = document.querySelector('[data-collector-review]').getBoundingClientRect()
        return { leftGap: preview.y - upload.bottom, rightGap: queue.y - controls.bottom }
      })
      if (Math.abs(columns.leftGap - 16) > 1 || Math.abs(columns.rightGap - 16) > 1) throw Error('Columns contain artificial empty space: ' + JSON.stringify(columns))
      await page.getByText('Recorded samples (1)', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'Prepare training package', exact: true }).waitFor()
      await page.screenshot({ path: path.join(output, 'final-boundary-desktop.png'), fullPage: true })
      await page.setViewportSize({ width: 390, height: 844 })
      await page.screenshot({ path: path.join(output, 'final-boundary-mobile.png'), fullPage: true })
      if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) throw Error('Boundary layout overflows viewport')
      console.log('Boundary layout passed: independent columns, scoped saved samples, training export, desktop and 390px.')
    }
    if (errors.length) throw Error('Page errors: ' + errors.join('; '))
    console.log('Layout check passed: desktop, 390px layout, navigation focus/Escape/backdrop, settings, saved exports, training download and recorded-sample deletion. Main width: ' + mainWidth)
  } finally { await browser?.close(); await server.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
